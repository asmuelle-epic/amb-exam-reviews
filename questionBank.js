  function normalize(text) {
    return (text || '')
      .toLowerCase()
      .replace(/[‘’]/g, "'")
      .replace(/[“”]/g, '"')
      .replace(/[^a-z0-9]+/g, ' ')
      .trim();
  }

  // 32-bit FNV-1a, written out in base 36.
  function hash(str) {
    let h = 0x811c9dc5;
    for (let i = 0; i < str.length; i++) {
      h ^= str.charCodeAt(i);
      h = Math.imul(h, 0x01000193) >>> 0;
    }
    return h.toString(36);
  }

  function fingerprint(text) {
    const words = normalize(text).split(' ').filter(Boolean);
    const chunks = new Set();
    if (words.length === 0) return [];
    if (words.length < 3) {
      chunks.add(words.join(' '));
    } else {
      for (let i = 0; i + 3 <= words.length; i++) chunks.add(words.slice(i, i + 3).join(' '));
    }
    return Array.from(new Set(Array.from(chunks, hash))).sort();
  }

