  /* Finds the best bank entry for a pasted question stem in the given exam.
     Returns { subName, pool, ref, score } or null. subName is already
     translated to the exam's own subtopic name. */
  function match(examId, stem, subtopicExists) {
    const pools = DATA.examPools[examId] || [];
    const pasted = new Set(fingerprint(stem));
    if (pasted.size === 0) return null;
    let best = null;
    for (const pool of pools) {
      for (const entry of (DATA.pools[pool] || [])) {
        const score = containment(entry.fp, pasted);
        // Short questions share most of their wording with other questions
        // ("What is the row type of ..."), so they must match completely.
        const required = entry.fp.length <= SHORT_FP ? 1 : MIN_SCORE;
        if (score < required || (best && score <= best.score)) continue;
        const alias = (DATA.aliases[examId] || {})[entry.sub];
        const subName = subtopicExists(entry.sub) ? entry.sub : (alias && subtopicExists(alias) ? alias : null);
        if (!subName) continue;
        best = { subName, pool, ref: entry.ref || '', score };
      }
    }
    return best;
  }

