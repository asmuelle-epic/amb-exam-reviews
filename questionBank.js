/* ---------------- Question bank ----------------
   Known exam questions mapped to the subtopic that reviews them.

   No question text is stored here. Each question is saved only as a
   fingerprint: its stem is normalized, split into overlapping 3-word
   chunks, and each chunk is hashed. A pasted question is fingerprinted
   the same way in the browser and compared against these entries, so a
   match still works with small differences (punctuation, a typo, an
   extra header line), but the questions can't be read back out of this
   file.

   Pools group questions by where they come from. examPools says which
   pools each exam template searches, so one mapping can serve several
   exams (for example, CLN questions are reused on the CEE exam).

   aliases translate a subtopic name from a pool's home exam to the name
   used in another exam (CLN 251-252 and CEE name some subtopics
   differently).

   Entries are added with tools/qb.js. Edit the data block by hand only if
   you know what you're changing: the tool rewrites everything between the
   QB-DATA markers. */

